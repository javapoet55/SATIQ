import {test,expect} from '@playwright/test';
const KEY = 'waypoint-local-v1';
test('daily plan → hints → checked questions → confirmed review → completed plan', async ({page}) => {
  await page.goto('/#plan');
  await page.getByRole('button',{name:'10 min',exact:true}).click();
  await expect(page.locator('.plan-progress')).toContainText('0 of 3 activities');
  await page.getByRole('button',{name:'Start: Find your algebra rhythm',exact:true}).click();
  await expect(page).toHaveURL(/#tutor$/);
  await expect(page.getByRole('button',{name:'Complete demo activity & return to plan'})).toBeDisabled();
  await expect(page.getByRole('button',{name:'Discuss my choice'})).toBeDisabled();
  await page.getByRole('button',{name:'Give me a small hint'}).click();
  await page.getByRole('button',{name:'Next small hint'}).click();
  await page.getByRole('button',{name:'Next small hint'}).click();
  await expect(page.getByRole('button',{name:'All 3 hints opened'})).toBeDisabled();
  await expect(page.getByText('3 of 3 hints opened')).toBeVisible();
  await page.getByRole('radio',{name:'A. 4 days',exact:true}).check();
  await page.getByRole('button',{name:'Check answer'}).click();
  await expect(page.getByText('↻ Let’s learn from this one.',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Complete demo activity & return to plan'}).click();
  await expect(page.locator('.plan-progress')).toContainText('1 of 3 activities');
  await page.reload();
  await expect(page.getByRole('button',{name:'10 min',exact:true})).toHaveAttribute('aria-pressed','true');
  await expect(page.locator('.plan-progress')).toContainText('1 of 3 activities');
  await page.getByRole('button',{name:'Start: Connect the ideas',exact:true}).click();
  await page.getByRole('radio',{name:'C. as a result',exact:true}).check();
  await page.getByRole('button',{name:'Check answer'}).click();
  await page.getByRole('button',{name:'Complete demo activity & return to plan'}).click();
  await page.getByRole('button',{name:'Start: Turn an attempt into a lesson',exact:true}).click();
  await expect(page.getByText('Your answer: A · 4 days',{exact:true})).toBeVisible();
  await expect(page.getByRole('button',{name:'Explore my mistake'})).toBeDisabled();
  await page.getByRole('button',{name:'Use example reflection'}).click();
  await page.getByRole('button',{name:'Explore my mistake'}).click();
  await page.getByRole('radio',{name:/Concept gap/}).check();
  await page.getByRole('button',{name:'Confirm my reflection'}).click();
  await expect(page.getByRole('heading',{name:'Separate the parts.'})).toBeVisible();
  await page.getByRole('radio',{name:/Question misunderstanding/}).check();
  await expect(page.getByRole('heading',{name:'Separate the parts.'})).toHaveCount(0);
  await page.getByRole('button',{name:'Confirm my reflection'}).click();
  await expect(page.getByRole('heading',{name:'Name what you need to find.'})).toBeVisible();
  await page.reload();
  await expect(page.getByRole('heading',{name:'Name what you need to find.'})).toBeVisible();
  await page.getByRole('button',{name:'Complete review & return to plan',exact:true}).click();
  await expect(page.locator('.plan-progress')).toContainText('3 of 3 activities');
  await page.getByRole('button',{name:'30 min',exact:true}).click();
  await expect(page.locator('.plan-progress')).toContainText('3 of 4 activities');
  await expect(page.getByRole('button',{name:'Start: A little extra stretch'})).toBeEnabled();
  await page.getByRole('button',{name:'10 min',exact:true}).click();
  await expect(page.locator('.plan-progress')).toContainText('3 of 3 activities');
  const saved = await page.evaluate(key => JSON.parse(localStorage.getItem(key)!),KEY);
  expect(saved.attempts).toHaveLength(2);
  expect(Object.values(saved.companion.plans)[0]).toMatchObject({minutes:10});
});
test('tutor saves drafts and literal custom text, resets context on subject switch, preserves attempts', async ({page}) => {
  await page.goto('/#tutor');
  await page.getByRole('button',{name:'Give me a small hint'}).click();
  const custom = '<img src=x onerror="alert(1)"> & explain this <step>';
  await page.getByRole('textbox',{name:'Your question to the tutor'}).fill(custom);
  await page.reload();
  await expect(page.getByRole('textbox',{name:'Your question to the tutor'})).toHaveValue(custom);
  await expect(page.getByText('1 of 3 hints opened')).toBeVisible();
  await page.getByRole('button',{name:'Send question'}).click();
  await expect(page.getByRole('log')).toContainText(custom);
  await expect(page.getByRole('log').locator('img')).toHaveCount(0);
  await expect(page.getByRole('log')).toContainText('custom questions are not interpreted');
  await page.getByRole('radio',{name:'A. 4 days',exact:true}).check();
  await page.getByRole('button',{name:'Check answer'}).click();
  await page.getByRole('button',{name:'Reading & Writing',exact:true}).click();
  await expect(page.getByText('0 of 3 hints opened')).toBeVisible();
  await expect(page.getByRole('log')).not.toContainText(custom);
  await page.getByRole('button',{name:'Math',exact:true}).click();
  await expect(page.getByRole('radio',{checked:true})).toHaveCount(0);
  await expect(page.getByRole('button',{name:'Check answer'})).toBeDisabled();
  const saved = await page.evaluate(key => JSON.parse(localStorage.getItem(key)!),KEY);
  expect(saved.attempts).toHaveLength(1); expect(saved.attempts[0].correct).toBe(false);
});
test('sample analysis and past/future previews never fabricate completed activity', async ({page}) => {
  await page.goto('/#analysis');
  await page.getByRole('button',{name:'Explore sample mistake'}).click();
  await expect(page.getByText('Illustrative · not in progress')).toBeVisible();
  await page.getByRole('button',{name:'Use example reflection'}).click();
  await page.getByRole('button',{name:'Explore my mistake'}).click();
  await page.getByRole('button',{name:'Confirm my reflection'}).click();
  await page.getByRole('button',{name:'Daily Plan',exact:true}).click();
  await expect(page.locator('.plan-progress')).toContainText('0 of 3 activities');
  await expect(page.getByText('0 days',{exact:true})).toBeVisible();
  const todayIndex = await page.locator('.schedule button').evaluateAll(buttons => buttons.findIndex(b => b.getAttribute('aria-label')?.includes('today')));
  const otherIndex = todayIndex === 6 ? 0 : 6;
  await page.locator('.schedule button').nth(otherIndex).click();
  await expect(page.locator('.plan-task button').first()).toBeDisabled();
  await expect(page.getByRole('button',{name:'10 min',exact:true})).toBeDisabled();
  const saved = await page.evaluate(key => JSON.parse(localStorage.getItem(key)!),KEY);
  expect(saved.attempts).toHaveLength(0);
});
